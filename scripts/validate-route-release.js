"use strict";

const fs = require("node:fs");
const { execFileSync } = require("node:child_process");
const { isDeepStrictEqual } = require("node:util");
const {
  renderRoutes,
  validateRouteUpdate,
} = require("./update-upstreams-routes");

const EXPECTED_FILES = Object.freeze([
  "package-lock.json",
  "package.json",
  "src/UpstreamRoutes.js",
]);

function clone(value) {
  return JSON.parse(JSON.stringify(value));
}

function parseStableVersion(version) {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(version);
  if (!match) throw new Error(`Expected a stable semantic version, received ${version}`);
  return match.slice(1).map(Number);
}

function validateManifestChanges(previousPackage, nextPackage, previousLockfile, nextLockfile) {
  const [previousMajor, previousMinor, previousPatch] = parseStableVersion(previousPackage.version);
  const [nextMajor, nextMinor, nextPatch] = parseStableVersion(nextPackage.version);
  if (
    nextMajor !== previousMajor ||
    nextMinor !== previousMinor ||
    nextPatch !== previousPatch + 1
  ) {
    throw new Error("package version must be an exact patch increment");
  }

  const normalizedPackage = clone(nextPackage);
  normalizedPackage.version = previousPackage.version;
  if (!isDeepStrictEqual(previousPackage, normalizedPackage)) {
    throw new Error("package.json may only change the version");
  }

  if (
    previousLockfile.version !== previousPackage.version ||
    previousLockfile.packages?.[""]?.version !== previousPackage.version ||
    nextLockfile.version !== nextPackage.version ||
    nextLockfile.packages?.[""]?.version !== nextPackage.version
  ) {
    throw new Error("package-lock.json root versions must match package.json");
  }

  const normalizedLockfile = clone(nextLockfile);
  normalizedLockfile.version = previousPackage.version;
  normalizedLockfile.packages[""].version = previousPackage.version;
  if (!isDeepStrictEqual(previousLockfile, normalizedLockfile)) {
    throw new Error("package-lock.json may only change root version fields");
  }
}

function parseRangeBlock(block) {
  return block.trimEnd().split("\n").map((line) => {
    const match = /^  (\d+),$/.exec(line);
    const value = match ? Number(match[1]) : NaN;
    if (!Number.isSafeInteger(value)) throw new Error("Route snapshot is not in generated format");
    return value;
  });
}

function parseRenderedRoutes(source) {
  const normalizedSource = source.replace(/\r\n/g, "\n");
  const match = normalizedSource.match(
    /^"use strict";\n\n\/\/ Generated by scripts\/update-upstreams-routes\.js from WB origin route maps\.\n\/\/ Do not edit manually\.\nconst MEDIA_BASKET_RANGES = Object\.freeze\(\[\n((?:  \d+,\n)+)\]\);\n\nconst VIDEO_BASKET_RANGES = Object\.freeze\(\[\n((?:  \d+,\n)+)\]\);\n\nmodule\.exports = \{\n  MEDIA_BASKET_RANGES,\n  VIDEO_BASKET_RANGES,\n\};\n$/
  );
  if (!match) throw new Error("Route snapshot is not in generated format");

  const routes = {
    mediaBasketRanges: parseRangeBlock(match[1]),
    videoBasketRanges: parseRangeBlock(match[2]),
  };
  if (renderRoutes(routes) !== normalizedSource) {
    throw new Error("Route snapshot is not in generated format");
  }
  return routes;
}

function git(args) {
  return execFileSync("git", args, { encoding: "utf8" }).trimEnd();
}

function readJsonFromGit(baseRef, filePath) {
  return JSON.parse(git(["show", `${baseRef}:${filePath}`]));
}

function validateRelease(baseRef) {
  if (!baseRef) throw new Error("A base git revision is required");

  const headWithParents = git(["rev-list", "--parents", "-n", "1", "HEAD"]).split(" ");
  const resolvedBase = git(["rev-parse", baseRef]);
  if (headWithParents.length !== 2 || headWithParents[1] !== resolvedBase) {
    throw new Error("Route release must be a single-parent commit based on the previous main");
  }

  const changedFiles = git(["diff", "--name-only", `${resolvedBase}..HEAD`])
    .split("\n")
    .filter(Boolean)
    .sort();
  if (!isDeepStrictEqual(changedFiles, [...EXPECTED_FILES])) {
    throw new Error(`Unexpected route release files: ${changedFiles.join(", ")}`);
  }

  const previousPackage = readJsonFromGit(resolvedBase, "package.json");
  const previousLockfile = readJsonFromGit(resolvedBase, "package-lock.json");
  const nextPackage = JSON.parse(fs.readFileSync("package.json", "utf8"));
  const nextLockfile = JSON.parse(fs.readFileSync("package-lock.json", "utf8"));
  validateManifestChanges(previousPackage, nextPackage, previousLockfile, nextLockfile);

  const previousRoutes = parseRenderedRoutes(
    git(["show", `${resolvedBase}:src/UpstreamRoutes.js`]) + "\n"
  );
  const nextRoutes = parseRenderedRoutes(fs.readFileSync("src/UpstreamRoutes.js", "utf8"));
  validateRouteUpdate(previousRoutes, nextRoutes);
}

if (require.main === module) {
  try {
    validateRelease(process.argv[2]);
    process.stdout.write("Validated automated route release\n");
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = {
  parseRenderedRoutes,
  validateManifestChanges,
  validateRelease,
};
