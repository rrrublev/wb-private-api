"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { request } = require("undici");

const DEFAULT_UPSTREAMS_URL = "https://cdn.wbbasket.ru/api/v3/upstreams";
const DEFAULT_OUTPUT_PATH = path.resolve(__dirname, "../src/UpstreamRoutes.js");

function getRangeRoute(upstreams, routeMapName) {
  const routes = upstreams?.origin?.[routeMapName];
  const rangeRoutes = Array.isArray(routes)
    ? routes.filter((item) => item?.method === "range")
    : [];
  if (rangeRoutes.length !== 1) {
    throw new Error(`origin.${routeMapName} must contain exactly one range route`);
  }
  const [route] = rangeRoutes;
  if (!Array.isArray(route.hosts) || route.hosts.length === 0) {
    throw new Error(`origin.${routeMapName} range route must contain hosts`);
  }
  return route;
}

function getRangeEnds(route, routeMapName) {
  let expectedStart = 0;
  return route.hosts.map((host, index) => {
    const from = host?.vol_range_from;
    const to = host?.vol_range_to;
    const rangeName = `${routeMapName} range ${index + 1}`;
    if (!Number.isSafeInteger(from) || !Number.isSafeInteger(to) || to < from) {
      throw new Error(`${rangeName} must have valid integer bounds`);
    }
    if (from !== expectedStart) {
      throw new Error(`${rangeName} must start at ${expectedStart}`);
    }
    expectedStart = to + 1;
    return to;
  });
}

function extractRoutes(upstreams) {
  return {
    mediaBasketRanges: getRangeEnds(
      getRangeRoute(upstreams, "mediabasket_route_map"),
      "mediabasket_route_map"
    ),
    videoBasketRanges: getRangeEnds(
      getRangeRoute(upstreams, "videonme_route_map"),
      "videonme_route_map"
    ),
  };
}

function formatRanges(ranges) {
  return ranges.map((range) => `  ${range},`).join("\n");
}

function renderRoutes({ mediaBasketRanges, videoBasketRanges }) {
  return `"use strict";\n\n// Generated by scripts/update-upstreams-routes.js from WB origin route maps.\n// Do not edit manually.\nconst MEDIA_BASKET_RANGES = Object.freeze([\n${formatRanges(mediaBasketRanges)}\n]);\n\nconst VIDEO_BASKET_RANGES = Object.freeze([\n${formatRanges(videoBasketRanges)}\n]);\n\nmodule.exports = {\n  MEDIA_BASKET_RANGES,\n  VIDEO_BASKET_RANGES,\n};\n`;
}

function parseArguments(args) {
  const options = { outputPath: DEFAULT_OUTPUT_PATH, url: DEFAULT_UPSTREAMS_URL };
  for (let index = 0; index < args.length; index += 1) {
    const option = args[index];
    const value = args[index + 1];
    if ((option === "--input" || option === "--output" || option === "--url") && value) {
      index += 1;
      if (option === "--input") options.inputPath = path.resolve(value);
      if (option === "--output") options.outputPath = path.resolve(value);
      if (option === "--url") options.url = value;
    } else {
      throw new Error(`Unknown or incomplete argument: ${option}`);
    }
  }
  return options;
}

async function loadUpstreams(options) {
  if (options.inputPath) {
    return JSON.parse(fs.readFileSync(options.inputPath, "utf8"));
  }

  const response = await request(options.url, {
    headers: { accept: "application/json" },
    headersTimeout: 10000,
    bodyTimeout: 10000,
  });
  if (response.statusCode !== 200) {
    throw new Error(`Unexpected upstreams response status: ${response.statusCode}`);
  }
  return response.body.json();
}

async function main(args = process.argv.slice(2)) {
  const options = parseArguments(args);
  const routes = extractRoutes(await loadUpstreams(options));
  fs.writeFileSync(options.outputPath, renderRoutes(routes));
  process.stdout.write(`Updated ${options.outputPath}\n`);
}

if (require.main === module) {
  main().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  });
}

module.exports = { extractRoutes, renderRoutes };
